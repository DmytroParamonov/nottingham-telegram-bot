def phase_help_text(
    *,
    phase: str,
    is_sheriff: bool,
    is_current_trader: bool = False,
    market_order_missing: bool = False,
    is_current_declarer: bool = False,
    resolved: bool = False,
) -> str:
    role = "🛡 Ти зараз <b>КОМАНДИР ВАРТИ</b>." if is_sheriff else "🐴 Ти зараз <b>КУПЕЦЬ</b>."

    if phase == "market":
        if is_sheriff and market_order_missing:
            action = (
                "Твоя дія — <b>обрати першого купця</b>. Після цього купці по черзі мінятимуть руку: "
                "скинуть 0–5 карт і доберуть до 6. Сам ти цього раунду не торгуєш."
            )
        elif is_sheriff:
            action = "Купці зараз торгують. Ти лише спостерігаєш і чекаєш, поки кожен завершить свій хід."
        elif is_current_trader:
            action = (
                "Зараз <b>твоя черга</b>. Переглянь 6 товарів, скинь 0–5 непотрібних і підтвердь хід. "
                "Бот автоматично добере нові карти до 6."
            )
        else:
            action = "Зараз торгує інший купець. Нічого натискати не треба — дочекайся своєї черги."
        return f"🛒 <b>ТОРГ НА РИНКУ</b>\n━━━━━━━━━━━━━━━━━━━━\n{role}\n\n{action}"

    if phase == "packing":
        action = (
            "Купці таємно готують повозки. Тобі зараз нічого робити не треба."
            if is_sheriff
            else (
                "Поклади у вантаж <b>1–5 товарів</b>. Дозволені товари можна везти легально. "
                "Контрабанду, наприклад 🧬 Мутаген, законно провозити не можна — але ти можеш сховати її у вантажі й спробувати провести обманом. "
                "Потім натисни «Запечатати вантаж» — після цього передумати не можна."
            )
        )
        return f"🛞 <b>ЗАВАНТАЖЕННЯ ВОЗА</b>\n━━━━━━━━━━━━━━━━━━━━\n{role}\n\n{action}"

    if phase == "declaration":
        if is_sheriff:
            action = (
                "Слухай декларації купців. Вони <b>зобов'язані назвати точну кількість карт</b>, але можуть брехати про вміст. "
                "Заявити вони можуть лише один дозволений товар; контрабанду на кшталт 🧬 Мутагену декларувати не можна. "
                "Запам'ятовуй підозрілі заяви — скоро вирішуватимеш, кого обшукувати."
            )
        elif is_current_declarer:
            action = (
                "Зараз <b>твоя черга</b>. Кількість карт у вантажі має бути абсолютно точною — про неї брехати не можна. "
                "Обери <b>один дозволений товар</b>, який заявляєш. Навіть якщо всередині 🧬 Мутаген або інша контрабанда, називати її в декларації заборонено."
            )
        else:
            action = "Декларує інший купець. Дочекайся своєї черги — бот дасть кнопку, коли вона настане."
        return f"📜 <b>ДЕКЛАРАЦІЯ БІЛЯ БРАМИ</b>\n━━━━━━━━━━━━━━━━━━━━\n{role}\n\n{action}"

    if phase == "inspection":
        if is_sheriff:
            action = (
                "Ти контролюєш браму. Для кожного купця виріши: <b>пропустити</b> чи <b>обшукати повозку</b>. "
                "Під час обшуку кожна карта порівнюється з декларацією. Навіть дозволений товар стане порушенням, якщо купець задекларував інший вид. "
                "Можеш приймати угоди й хабарі. Якщо весь вантаж чесний — штраф платиш ти."
            )
        elif resolved:
            action = "Твоя повозка вже пройшла рішення варти. Чекай завершення раунду або втручайся в чужі справи через угоди."
        else:
            action = (
                "Варта ще не вирішила долю твоєї повозки. Якщо всередині є контрабанда або товар, який не збігається з декларацією, обшук буде болючим. "
                "Можеш ризикнути або запропонувати крони/товари через <b>Угоди з вартою</b>."
            )
        return f"🛡 <b>ОГЛЯД ВАРТОЮ</b>\n━━━━━━━━━━━━━━━━━━━━\n{role}\n\n{action}"

    if phase == "finished":
        return "🏆 <b>БРАМУ ЗАЧИНЕНО</b>\n━━━━━━━━━━━━━━━━━━━━\nПартія завершилась. Дивись фінальний рахунок: крони + товари + бонуси."

    return f"ℹ️ <b>ПОТОЧНИЙ ЕТАП</b>\n━━━━━━━━━━━━━━━━━━━━\n{role}\n\nОнови свою панель або відкрий повні правила."
