from __future__ import annotations

from aiogram import F, Router
from aiogram.types import CallbackQuery


router = Router(name="rules_help")


RULES_TEXT = """📜 <b>ЯК ГРАТИ — ДЛЯ НОВАЧКІВ</b>
━━━━━━━━━━━━━━━━━━━━

🎯 <b>МЕТА ГРИ</b>
Зароби найбільше очок. У фіналі рахуються твої монети, вартість товарів на прилавку, успішно провезена контрабанда та бонуси Короля/Королеви за дозволені товари.

👥 <b>ХТО ЩО РОБИТЬ?</b>
У кожному раунді один гравець — 👮 <b>Шериф</b>, усі інші — 🧺 <b>торговці</b>.
Торговці намагаються провести товари через ворота. Шериф вирішує: повірити, домовитися або перевірити мішок.
Після раунду роль Шерифа переходить далі.

<b>РАУНД ІДЕ ТАК:</b>

1️⃣ <b>ТОРГІВЛЯ</b>
Торговці дивляться свої 6 карт.
Можна скинути від 0 до 5 непотрібних карт і добрати нові назад до 6.
👮 Шериф у цьому раунді не торгує.

2️⃣ <b>ЗБЕРИ МІШОК</b>
Кожен торговець таємно кладе в мішок <b>від 1 до 5 карт</b>.
Туди можна покласти дозволені товари, контрабанду або суміш різних товарів.
Після запечатування змінити мішок уже не можна.

3️⃣ <b>ДЕКЛАРАЦІЯ</b>
Тепер ти говориш Шерифу, що нібито лежить у мішку.
Є два правила:
• кількість карт треба назвати <b>точно</b>;
• назвати можна лише <b>один вид дозволеного товару</b>.

Наприклад: у мішку 2 яблука 🍎 + 1 контрабанда 🟥.
Можна заявити: <b>«3 яблука»</b>.
Про вміст мішка брехати — можна. Про кількість карт — ні.

4️⃣ <b>ХАБАРІ ТА УГОДИ</b>
До перевірки можна домовлятися з Шерифом. Наприклад:
• дати золото, щоб він не відкривав твій мішок;
• запропонувати товар;
• заплатити за перевірку чужого гравця;
• домовитися про інші умови, які дозволяє бот.
💬 Блефувати в переговорах дозволено.

5️⃣ <b>ОГЛЯД ШЕРИФОМ</b>
Для кожного мішка Шериф обирає:
✅ <b>ПРОПУСТИТИ</b> — мішок не відкривається, усі товари проходять на прилавок. Успішна контрабанда залишається прихованою.
🔍 <b>ПЕРЕВІРИТИ</b> — бот відкриває мішок і порівнює його з декларацією.

<b>Якщо торговець сказав правду:</b>
Шериф помилився і <b>платить торговцю штраф</b>.

<b>Якщо торговець збрехав:</b>
правильно задекларований товар проходить, а незаявлені або неправильні товари конфіскуються. <b>Торговець платить штраф Шерифу.</b>

🔄 <b>КІНЕЦЬ РАУНДУ</b>
Бот добирає карти до руки, змінює Шерифа і запускає новий раунд.
У грі на 4–5 гравців кожен побуває Шерифом 2 рази, на 3 гравців — 3 рази.

💡 <b>ГОЛОВНЕ ДЛЯ ПЕРШОЇ ПАРТІЇ</b>
Не намагайся запам'ятати все одразу. Бот показує тільки ті кнопки, які доступні тобі зараз.
Якщо ти торговець — збирай мішок, блефуй і торгуйся.
Якщо ти Шериф — слухай декларації, бери хабарі або лови брехунів 😈

🏆 Наприкінці бот сам підрахує очки та покаже переможця."""


@router.callback_query(F.data == "ui:rules")
async def ui_rules_for_beginners(callback: CallbackQuery) -> None:
    await callback.answer()
    await callback.message.answer(RULES_TEXT)
